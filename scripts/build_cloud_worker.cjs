// Produce one pasteable ES module for Cloudflare's dashboard editor.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const snapshot=JSON.parse(fs.readFileSync(path.join(root,'web/data/alliance-api.json'),'utf8'));
const ids=snapshot.members.map(m=>String(m.governor_id??m.fid));
const output='// Generated by scripts/build_cloud_worker.cjs; contains no credentials.\n'+fs.readFileSync(path.join(root,'web/personal-model.js'),'utf8')+'\n'+['kvk-catalog.js','kvk-gear.js','kvk-model.js'].map(name=>fs.readFileSync(path.join(root,'web',name),'utf8')).join('\n')+'\nconst ROSTER_IDS='+JSON.stringify(ids)+';\n'+fs.readFileSync(path.join(root,'backend/worker-api.js'),'utf8');
fs.writeFileSync(path.join(root,'web/cloudflare-worker.js'),output);
