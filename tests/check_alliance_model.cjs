const assert=require('node:assert/strict'),fs=require('node:fs');
const model=require('../web/alliance-model.js'),engine=require('../web/engine.js');
const snapshot=JSON.parse(fs.readFileSync('web/data/alliance-api.json'));
const bands=JSON.parse(fs.readFileSync('web/alliance-profiles.json')).bands;
let plan=model.mergeSnapshot(model.emptyPlan(),snapshot);
assert.equal(plan.players.length,98);assert(plan.players.every(p=>model.hasPosition(p.api)));
assert(plan.players.every(p=>p.group==='none'));
const person=plan.players[0];person.group='1';person.stats={march_capacity:123456,host_strength:1.25};person.attending=false;
plan.traps={'1':{x:750,y:850},'2':{x:800,y:850}};
person.travel['1']={seconds:17,returnSeconds:19,position:model.fingerprint(plan,person,'1')};
assert.equal(model.travel(plan,person).source,'Measured');
const renamed=model.clone(snapshot);renamed.members[0].nick_name='Renamed member';renamed.profiles[person.governorId].player.x++;
let merged=model.mergeSnapshot(plan,renamed);
assert.equal(merged.players[0].group,'1');assert.equal(merged.players[0].attending,false);
assert.equal(merged.players[0].stats.march_capacity,123456);
assert.equal(merged.players[0].api.name,'Renamed member');assert.equal(model.travel(merged,merged.players[0]).stale,true);
plan.comparisonGroup='1';const compiled=model.compile(plan,bands);assert.equal(compiled.roster.length,1);assert.equal(compiled.absent.length,1);
assert.equal(compiled.roster[0].outbound_s,17);assert.equal(compiled.roster[0].return_s,19);
assert.equal(compiled.roster[0].host_strength,1.25);engine.member(compiled.roster[0]);
let nearest=model.assignNearest(plan);assert.equal(nearest.plan.players[0].group,'1');assert.equal(nearest.assigned,97);
nearest=model.assignNearest(plan,new Set([person.governorId]));assert.equal(nearest.assigned,1);
const missing=model.clone(plan);missing.players[1].api.x=null;missing.players[1].api.y=null;
assert.equal(model.assignNearest(missing,new Set([missing.players[1].governorId])).skipped,1);
const tie=model.clone(plan);tie.players[1].api={...tie.players[1].api,x:775,y:850};
assert.equal(model.assignNearest(tie,new Set([tie.players[1].governorId])).skipped,1);
const removed=model.clone(snapshot);removed.members.shift();const withFormer=model.mergeSnapshot(plan,removed);
assert.equal(withFormer.players.length,98);assert.equal(withFormer.players.find(p=>p.governorId===person.governorId).active,false);
assert.equal(model.compile(withFormer,bands).roster.length,0);
assert.deepEqual(model.validatePlan(JSON.parse(JSON.stringify(plan))),plan);
const invalid=model.clone(plan);invalid.players.push(invalid.players[0]);assert.throws(()=>model.validatePlan(invalid),/Duplicate/);
invalid.players.pop();invalid.players[0].stats.join_slots=1.5;assert.throws(()=>model.validatePlan(invalid),/whole/);
const all=model.compile(model.mergeSnapshot(model.emptyPlan(),snapshot),bands);all.roster.forEach(engine.member);
plan.players[1].group='1';plan.comparisonGroup='1';const rows=model.compile(plan,bands).roster;
const matrix=model.joinTravelTimes(plan,rows);assert.equal(Object.keys(matrix).length,2);
assert(Number.isInteger(matrix[rows[0].name][rows[1].name]));
assert.throws(()=>engine.mechanics({join_travel_times:{x:{y:-1}}}),/travel/);
console.log('98-member CNQ import, stable IDs, measurements, nearest assignment and plan validation pass.');
